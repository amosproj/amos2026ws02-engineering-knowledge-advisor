from __future__ import annotations

from collections.abc import Mapping
from http import HTTPStatus
from typing import Any

from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, Field, field_validator
from starlette.background import BackgroundTask

DEFAULT_PROBLEM_TYPE: str = "about:blank"


class ProblemException(Exception):
    def __init__(self, problem: Problem, headers: dict[str, str] | None = None):
        self.problem = problem
        self.headers = dict(headers) if headers else None
        super().__init__(problem.detail or problem.title or problem.type)


# https://www.rfc-editor.org/rfc/rfc9457.html
class Problem(BaseModel):
    """RFC 9457 Problem object"""

    model_config = ConfigDict(
        extra="allow",  # RFC 9457 §3.2
        populate_by_name=True,
    )

    type: str = Field(
        default=DEFAULT_PROBLEM_TYPE,
        description="URI reference identifying the problem type.",
    )
    title: str | None = Field(
        default=None,
        description="Short, human-readable summary of the problem type.",
    )
    status: int | None = Field(
        default=None,
        ge=100,
        le=599,
        description="HTTP status code generated by the origin server.",
    )
    detail: str | None = Field(
        default=None,
        description="Human-readable explanation specific to this occurence.",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference identifying this specific occurence",
    )

    @field_validator("type")
    @classmethod
    def _type_not_empty(cls, v: str) -> str:
        return v or DEFAULT_PROBLEM_TYPE

    @classmethod
    def from_status(
        cls, status: int, detail: str | None = None, **extensions: Any
    ) -> Problem:
        """Build an 'about:blank' problem. Its title should match the status phrase (§4.2.1)"""
        return cls(
            type=DEFAULT_PROBLEM_TYPE,
            title=HTTPStatus(status).phrase,
            status=status,
            detail=detail,
            **extensions,
        )

    def to_response_body(self) -> dict[str, Any]:
        return self.model_dump(mode="json", exclude_none=True)


class ProblemResponse(JSONResponse):
    media_type = "application/problem+json"
    default_status = 500

    def __init__(
        self,
        problem: Problem | None = None,
        *,
        headers: Mapping[str, str] | None = None,
        background: BackgroundTask | None = None,
        **fields: Any,
    ) -> None:
        if problem is None:
            problem = Problem(**fields)
        elif fields:
            problem = Problem(**{**problem.model_dump(), **fields})

        status = problem.status if problem.status is not None else self.default_status
        problem = problem.model_copy(update={"status": status})

        self.problem = problem
        super().__init__(
            content=problem.to_response_body(),
            status_code=status,
            headers=headers,
            media_type=self.media_type,
            background=background,
        )

    @classmethod
    def from_status(
        cls,
        status: int,
        detail: str | None = None,
        *,
        headers: Mapping[str, str] | None = None,
        **extensions: Any,
    ) -> ProblemResponse:
        return cls(Problem.from_status(status, detail, **extensions), headers=headers)
